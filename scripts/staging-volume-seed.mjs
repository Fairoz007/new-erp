// STAGING ONLY — loads the performance data set (scripts/staging/volume-seed.sql).
//
//   node scripts/staging-volume-seed.mjs --pglite [--scale 0.05]
//       Local: applies every migration to an in-memory PGlite, bootstraps an organization and a
//       Super Admin, loads the data set at the given scale and times the queries the app runs
//       (old "load everything" path vs the paged / aggregated RPCs). Touches no remote project.
//
//   node scripts/staging-volume-seed.mjs --print --project-ref <staging-ref> [--scale 1]
//       Writes staging-volume-seed.<ref>.sql with the guard set, to paste into the SQL editor of
//       the STAGING project. Refuses the production ref. This script never connects to Supabase.
//
// Production (fpeniljpqigpeqtsgizr) is refused in every mode.
import { readFileSync, writeFileSync } from 'fs';

const PRODUCTION_REF = 'fpeniljpqigpeqtsgizr';
const args = process.argv.slice(2);
const opt = (name, dflt) => { const i = args.indexOf(name); return i >= 0 ? args[i + 1] : dflt; };
const scale = Number(opt('--scale', args.includes('--pglite') ? '0.05' : '1'));
if (!(scale > 0 && scale <= 1)) { console.error('--scale must be in (0, 1]'); process.exit(2); }

const envText = [process.env.SUPABASE_URL, process.env.VITE_SUPABASE_URL, opt('--project-ref', '')].join(' ');
if (envText.includes(PRODUCTION_REF)) {
  console.error(`Refusing: ${PRODUCTION_REF} is the production project. This data set is for staging only.`);
  process.exit(3);
}

const seedSql = readFileSync(new URL('./staging/volume-seed.sql', import.meta.url), 'utf8').replaceAll('__SCALE__', String(scale));

if (args.includes('--print')) {
  const ref = opt('--project-ref');
  if (!ref) { console.error('--print needs --project-ref <staging project ref>'); process.exit(2); }
  const out = `staging-volume-seed.${ref}.sql`;
  writeFileSync(out, `-- STAGING ONLY (${ref}). Generated by scripts/staging-volume-seed.mjs at scale ${scale}.\n` +
    `begin;\nset local statement_timeout = 0;\nselect set_config('app.volume_seed_ok', 'staging', true);\n${seedSql}\ncommit;\n`);
  console.log(`Wrote ${out}. Open the SQL editor of the staging project ${ref} and run it there.`);
  process.exit(0);
}

if (!args.includes('--pglite')) {
  console.error('Choose --pglite (local measurement) or --print --project-ref <staging-ref>.');
  process.exit(2);
}

const { setup } = await import('../supabase/tests/harness.mjs');
const { readdirSync } = await import('fs');
const ADMIN = '00000000-0000-0000-0000-0000000000aa';
// --split <migration prefix>: build the database with the migrations BEFORE that prefix, time the
// "before" queries, then apply the remaining migrations and time the "after" queries, all on the
// same data. Without it every migration is applied first and only "after" queries run.
const split = opt('--split');
const allMigrations = readdirSync('supabase/migrations').filter(f => f.endsWith('.sql')).sort();
const t = await setup('supabase/migrations', { quiet: true, order: files => (split ? files.filter(f => f < split) : files) });
const { db } = t;
await db.exec(`
  select set_config('request.uid', '', false);
  insert into public.organizations (legal_name, base_currency) select 'Staging volume org', 'OMR' where not exists (select 1 from public.organizations);
  insert into auth.users (id, email) values ('${ADMIN}', 'volume-admin@staging.test');
  update public.profiles set role_id = (select id from public.roles where is_super limit 1), role = 'Super Admin' where id = '${ADMIN}';
`);
const t0 = Date.now();
try { await db.exec(`begin; select set_config('app.volume_seed_ok', 'staging', true); ${seedSql}; commit;`); }
catch (e) { console.error('Seed failed:', e.message, e.where ?? ''); process.exit(1); }
console.log(`Loaded scale ${scale} in ${((Date.now() - t0) / 1000).toFixed(1)} s`);
await db.exec('analyze');
const counts = (await db.query(`select
  (select count(*)::int from companies where code like 'VOL%') offices, (select count(*)::int from vehicles) vehicles,
  (select count(*)::int from employees) employees, (select count(*)::int from invoices) invoices,
  (select count(*)::int from journal_lines) journal_lines, (select count(*)::int from audit_logs) audit_logs`)).rows[0];
console.log(counts);

// Time the queries the browser issues, as the Super Admin. Each runs 3 times; the median is shown.
const queries = (await import('./staging/volume-queries.mjs')).default;
const median = xs => xs.sort((a, b) => a - b)[Math.floor(xs.length / 2)];
const results = [];
const only = opt('--only');
const runPass = async (phase) => {
for (const q of queries) {
  if (!q.name.startsWith(phase)) continue;
  if (only && !q.name.includes(only)) continue;
  const times = []; let info = {};
  for (let k = 0; k < (q.repeat ?? 3); k++) {
    const s = performance.now();
    try { info = await q.run(sql => t.as(ADMIN, sql)); } catch (e) { info = { error: e.message }; }
    times.push(performance.now() - s);
  }
  results.push({ query: q.name, ms: Math.round(median(times)), ...info });
}
};
if (split) {
  await runPass('before');
  for (const f of allMigrations.filter(f => f >= split)) { await db.exec(readFileSync(`supabase/migrations/${f}`, 'utf8')); console.log('applied', f); }
  await db.exec('analyze');
}
await runPass('after');
console.table(results);
if (args.includes('--json')) writeFileSync(opt('--json'), JSON.stringify({ scale, counts, results }, null, 2));
process.exit(0);
